import { analyseSimulatedDataset } from '@/lib/simulation/analysis';
import {
    formatInterval,
    formatPercent,
    formatPercentagePoints,
    formatSeconds,
    formatSignedPercent,
    VERDICT_TEXT,
} from '@/lib/simulation/format';
import { loadSimulatedDataset } from '@/lib/simulation/load-dataset';
import type { ConversionComparison } from '@/lib/stats/conversion';

function conversionLines(title: string, comparison: ConversionComparison): string[] {
    const { control, treatment } = comparison;
    return [
        title,
        `  Control:      ${control.conversions}/${control.visitors} = ${formatPercent(control.observedRate)}  (95% CrI ${formatInterval(control.credibleInterval, formatPercent)})`,
        `  Social proof: ${treatment.conversions}/${treatment.visitors} = ${formatPercent(treatment.observedRate)}  (95% CrI ${formatInterval(treatment.credibleInterval, formatPercent)})`,
        `  Absolute difference: ${formatPercentagePoints(comparison.observedAbsoluteDifference)}  (95% CrI ${formatInterval(comparison.absoluteDifference.credibleInterval, formatPercentagePoints)})`,
        `  Relative lift: ${formatSignedPercent(comparison.observedRelativeLift)}  (95% CrI ${formatInterval(comparison.relativeLift.credibleInterval, formatSignedPercent)})`,
        `  P(social proof beats control): ${formatPercent(comparison.probabilityTreatmentBeatsControl)}`,
        `  Supplementary verdict: ${VERDICT_TEXT[comparison.verdict]}`,
    ];
}

async function main() {
    const result = await loadSimulatedDataset(process.argv[2]);
    if (result.status !== 'loaded') {
        console.error(
            result.status === 'missing'
                ? `No simulated dataset at ${result.path}. Run the simulator first.`
                : `Invalid simulated dataset at ${result.path}: ${result.message}`,
        );
        process.exitCode = 1;
        return;
    }

    const analysis = analyseSimulatedDataset(result.dataset);
    const { sampleRatio, timeToClick } = analysis;
    const banner = `=== ${analysis.label} ===`;
    console.log(
        [
            banner,
            'Generated by the simulator, not real students. Official results are in Flagsmith.',
            `Dataset seed ${analysis.seed}, generated ${analysis.generatedAt}, ${analysis.totalVisitors} simulated visitors.`,
            '',
            ...conversionLines('Signup completion (signed_up)', analysis.signedUp),
            '',
            ...conversionLines('Signup click-through (signup_clicked)', analysis.clickedSignUp),
            '',
            'Sample ratio (expected 50/50)',
            sampleRatio.status === 'not_checked'
                ? `  Not checked: ${sampleRatio.reason} (control ${sampleRatio.control}, social proof ${sampleRatio.treatment})`
                : `  Control ${sampleRatio.control} (expected ${sampleRatio.expectedControl}), social proof ${sampleRatio.treatment} (expected ${sampleRatio.expectedTreatment}); chi-square ${sampleRatio.chiSquare.toFixed(2)}, p = ${sampleRatio.pValue.toPrecision(3)}: ${sampleRatio.status === 'mismatch' ? 'SRM WARNING' : 'no SRM detected'}`,
            '',
            'Time to signup click, clickers only (supplementary; the official Flagsmith metric counts non-clickers as 0 s)',
            ...(['control', 'social_proof'] as const).map((variant) => {
                const summary = timeToClick[variant];
                return `  ${variant}: ${summary.clickers} clickers, mean ${formatSeconds(summary.clickerMean)}, median ${formatSeconds(summary.clickerMedian)} (zero-filled mean as Flagsmith computes it: ${formatSeconds(summary.zeroFilledMean)})`;
            }),
            banner,
        ].join('\n'),
    );
}

void main();
