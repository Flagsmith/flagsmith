/**
 * Generate icon components from SVGs exported from the Figma icon library.
 *
 * Export each icon component from Figma as SVG, named like the component
 * (trash.svg, chevron-down.svg), into one folder. Each SVG becomes
 * web/components/icons/<Name>Icon.tsx, and the generated icons are
 * re-exported from web/components/icons/index.ts.
 *
 * Usage:
 *   node scripts/generate-icons.mjs <folder of svgs>
 *   npm run generate:icons -- <folder of svgs>
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { resolve, dirname, basename } from 'node:path'
import { fileURLToPath } from 'node:url'
import { execSync } from 'node:child_process'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')
const ICONS = resolve(ROOT, 'web/components/icons')
const HEADER = '// Generated by scripts/generate-icons.mjs'
const INDEX_MARKER = '// Icon library, generated by scripts/generate-icons.mjs'

const source = process.argv[2]
if (!source) {
  console.error('Usage: node scripts/generate-icons.mjs <folder of svgs>')
  process.exit(1)
}

const ATTRIBUTES = {
  'clip-rule': 'clipRule',
  'fill-rule': 'fillRule',
  'stroke-linecap': 'strokeLinecap',
  'stroke-linejoin': 'strokeLinejoin',
  'stroke-miterlimit': 'strokeMiterlimit',
  'stroke-width': 'strokeWidth',
}

const componentName = (file) =>
  `${basename(file, '.svg')
    .split('-')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('')}Icon`

// Figma exports may wrap the icon in its frame, so take the drawn shapes only
const toJsx = (svg) =>
  [...svg.matchAll(/<(path|circle|line)\b([^>]*?)\/?>/g)]
    .map(([, tag, attributes]) => {
      const props = [...attributes.matchAll(/([\w-]+)="([^"]*)"/g)]
        .filter(([, key]) => key !== 'id')
        .map(([, key, value]) =>
          (key === 'stroke' || key === 'fill') && value.startsWith('#')
            ? `${key}={fill}`
            : `${ATTRIBUTES[key] ?? key}='${value}'`,
        )
      return `<${tag} ${props.join(' ')} />`
    })
    .join('\n')

const component = (name, shapes) => `${HEADER}
import { FC } from 'react'
import { IconProps } from './types'

const ${name}: FC<IconProps> = ({
  fill = 'currentColor',
  height,
  width = 24,
  ...rest
}) => (
  <svg
    width={width}
    height={height ?? width}
    viewBox='0 0 24 24'
    fill='none'
    xmlns='http://www.w3.org/2000/svg'
    aria-hidden={rest['aria-label'] || rest['aria-labelledby'] ? undefined : true}
    {...rest}
  >
    ${shapes}
  </svg>
)

export default ${name}
`

const written = readdirSync(source)
  .filter((file) => file.endsWith('.svg'))
  .map((file) => {
    const name = componentName(file)
    const shapes = toJsx(readFileSync(resolve(source, file), 'utf-8'))
    writeFileSync(resolve(ICONS, `${name}.tsx`), component(name, shapes))
    return `web/components/icons/${name}.tsx`
  })

// Re-export every generated icon, including ones from earlier runs
const generated = readdirSync(ICONS)
  .filter(
    (file) =>
      file.endsWith('Icon.tsx') &&
      readFileSync(resolve(ICONS, file), 'utf-8').startsWith(HEADER),
  )
  .map((file) => basename(file, '.tsx'))
  .sort()
const indexPath = resolve(ICONS, 'index.ts')
const index = readFileSync(indexPath, 'utf-8')
const handWritten = index.includes(INDEX_MARKER)
  ? index.slice(0, index.indexOf(INDEX_MARKER))
  : index
writeFileSync(
  indexPath,
  `${handWritten.trimEnd()}\n\n${INDEX_MARKER}\n${generated
    .map((name) => `export { default as ${name} } from './${name}'`)
    .join('\n')}\nexport type { IconComponent, IconProps } from './types'\n`,
)

execSync(
  `npx prettier --write ${[...written, 'web/components/icons/index.ts'].join(
    ' ',
  )}`,
  { cwd: ROOT, stdio: 'inherit' },
)
console.log(`Generated ${written.length} icons`)
