-- Snowflake schema for experimentation events.
CREATE SCHEMA IF NOT EXISTS FLAGSMITH_EXP;

CREATE TABLE IF NOT EXISTS FLAGSMITH_EXP.EVENTS (
    ENVIRONMENT_KEY STRING NOT NULL,
    EVENT           STRING NOT NULL,
    FEATURE_NAME    STRING,
    TIMESTAMP       TIMESTAMP_NTZ NOT NULL,
    COLLECTED_AT    TIMESTAMP_NTZ,
    IDENTIFIER      STRING NOT NULL,
    VALUE           STRING,
    TRAITS          STRING,
    METADATA        STRING,
    SDK_LANGUAGE    STRING,
    SDK_VERSION     STRING
);
